// CodepageFor elige la tabla según el language driver del header. Solo
// CP850 y CP1252: con cualquier otro (incluido 0x00) no se adivina.
// Devuelve una copia: las tablas del paquete no se comparten mutables.
func CodepageFor(driver byte) (Codepage, error) {
	switch driver {
	case 0x02:
		return cp850, nil
	case 0x03, 0x57:
		return cp1252, nil
	default:
		return Codepage{}, fmt.Errorf("language driver 0x%02X sin tabla: no se adivina el encoding", driver)
	}
}

// Decode convierte bytes de la página de códigos a UTF-8.
func (c *Codepage) Decode(raw []byte) string {
	var out strings.Builder

	out.Grow(len(raw) + len(raw)/4)

	for _, b := range raw {
		if b < utf8.RuneSelf {
			out.WriteByte(b)
			continue
		}

		out.WriteRune(c.high[b-0x80])
	}

	return out.String()
}
